# Requirement Coverage Engine (E7.6/E7.7/E7.8/E7.9) -- deterministic,
# no LLM call, never trusts a model-provided coverage total
# ===================================================================
class RequirementCoverageService:
    def __init__(self, trace, test_case_specs: TestCaseSpecStore, specs_root):
        self.trace = trace
        self.test_case_specs = test_case_specs
        self.specs_root = specs_root

    def governing_feature_ids(self, change_id: int) -> list[str]:
        return [l["target_id"] for l in self.trace.for_source("change", change_id) if l["target_type"] == "spec_feature"]

    def compute(self, change_id: int) -> dict:
        from app.services.spec_registry import SpecRegistry, SpecError
        req_ids: set[str] = set()
        acc_ids: set[str] = set()
        inv_ids: set[str] = set()
        try:
            registry = SpecRegistry(self.specs_root).load()
            for fid in self.governing_feature_ids(change_id):
                f = registry.feature(fid)
                if not f:
                    continue
                req_ids.update(r["id"] for r in (f.get("requirements") or []))
                acc_ids.update(a["id"] for a in (f.get("acceptance_criteria") or []))
                inv_ids.update(i["id"] for i in (f.get("invariants") or []))
        except SpecError:
            pass

        cases = self.test_case_specs.list_for_change(change_id)
        covered_req: set[str] = set()
        covered_acc: set[str] = set()
        covered_inv: set[str] = set()
        invalid_references: list[dict] = []
        automation_candidates = 0
        manual_only_items = 0
        negative_cases = 0
        for tc in cases:
            for kind, col, universe, covered in (
                ("requirement", "requirement_ids", req_ids, covered_req),
                ("acceptance", "acceptance_ids", acc_ids, covered_acc),
                ("invariant", "invariant_ids", inv_ids, covered_inv),
            ):
                for ref in json.loads(tc[col] or "[]"):
                    if ref in universe:
                        covered.add(ref)
                    else:
                        invalid_references.append({"kind": kind, "id": ref, "test_case_key": tc["item_key"]})
            if tc["automation_candidate"]:
                automation_candidates += 1
            if tc["test_type"] == "MANUAL_ACCEPTANCE" or tc["test_level"] == "MANUAL_ACCEPTANCE":
                manual_only_items += 1
            if tc["test_type"] == "NEGATIVE":
                negative_cases += 1

        return {
            "change_id": change_id,
            "requirements_total": len(req_ids), "requirements_covered": sorted(covered_req),
            "requirements_uncovered": sorted(req_ids - covered_req),
            "acceptance_total": len(acc_ids), "acceptance_covered": sorted(covered_acc),
            "acceptance_uncovered": sorted(acc_ids - covered_acc),
            "invariants_total": len(inv_ids), "invariants_covered": sorted(covered_inv),
            "invariants_uncovered": sorted(inv_ids - covered_inv),
            "automation_candidates": automation_candidates, "manual_only_items": manual_only_items,
            "negative_cases": negative_cases, "test_case_count": len(cases),
            "invalid_references": invalid_references,
        }



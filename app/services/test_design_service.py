def _resolve_id_collisions_free(items: list[str]) -> list[str]:
    """No collision remapping needed for id REFERENCES (unlike E5's
    authored ids) -- just dedupe while preserving order."""
    seen: set[str] = set()
    out: list[str] = []
    for it in items or []:
        s = (it or "").strip()
        if s and s not in seen:
            seen.add(s)
            out.append(s)
    return out


class _TestAgentRole:
    """Shared plumbing for every E7 agent role -- same shape as E5/E6's
    own _AgentRole, duplicated rather than imported so this module stays
    self-contained."""

    def __init__(self, db, invoker, roles_catalog, role_key):
        self.db = db
        self.invoker = invoker
        self.roles_catalog = roles_catalog
        self.role_key = role_key

    def _check_assignment(self, provider):
        assignment = self.roles_catalog.validate_assignment(provider, self.role_key)
        if not assignment["valid"]:
            raise TestDesignError(f"Provider '{provider}' cannot act as {self.role_key}: missing {assignment['missing_required_capabilities']}")


# ===================================================================
# TestCaseSpec store -- a thin domain/table (E7.3) over test_case_specs
# ===================================================================
class TestCaseSpecStore:
    def __init__(self, db):
        self.db = db

    def get(self, tcs_id: int) -> dict | None:
        return self.db.one("SELECT * FROM test_case_specs WHERE id=?", (tcs_id,))

    def list_for_change(self, change_id: int, current_only: bool = True) -> list[dict]:
        if current_only:
            return self.db.all("SELECT * FROM test_case_specs WHERE change_id=? AND status!='SUPERSEDED' ORDER BY id", (change_id,))
        return self.db.all("SELECT * FROM test_case_specs WHERE change_id=? ORDER BY id", (change_id,))

    def list_for_work_product(self, work_product_id: int) -> list[dict]:
        return self.db.all("SELECT * FROM test_case_specs WHERE work_product_id=? ORDER BY id", (work_product_id,))

    def set_status(self, tcs_id: int, status: str) -> dict:
        status = (status or "").strip().upper()
        if status not in TEST_CASE_STATUSES:
            raise TestDesignError(f"Unknown status: {status} (must be one of {TEST_CASE_STATUSES})")
        if not self.get(tcs_id):
            raise TestDesignError("TestCaseSpec not found")
        self.db.execute("UPDATE test_case_specs SET status=?,updated_at=CURRENT_TIMESTAMP WHERE id=?", (status, tcs_id))
        return self.get(tcs_id)

    def set_status_for_work_product(self, work_product_id: int, status: str) -> None:
        for row in self.list_for_work_product(work_product_id):
            self.set_status(row["id"], status)


# ===================================================================
# Bounded Test Design context (mirrors ArchitectureContextBuilder, E6.4)
# ===================================================================
class TestDesignContextBuilder:
    def __init__(self, db, changes, work_products, trace, test_case_specs: TestCaseSpecStore, specs_root):
        self.db = db
        self.changes = changes
        self.work_products = work_products
        self.trace = trace
        self.test_case_specs = test_case_specs
        self.specs_root = specs_root

    def governing_feature_ids(self, change_id: int) -> list[str]:
        return [l["target_id"] for l in self.trace.for_source("change", change_id) if l["target_type"] == "spec_feature"]

    def build(self, change_id: int, project_test_command: dict | None = None) -> dict:
        from app.services.spec_registry import SpecRegistry, SpecError
        change = self.changes.get(change_id)
        governing_ids = self.governing_feature_ids(change_id)
        governing_specs: list[dict] = []
        all_requirement_ids: list[str] = []
        all_acceptance_ids: list[str] = []
        all_invariant_ids: list[str] = []
        try:
            registry = SpecRegistry(self.specs_root).load()
            for fid in governing_ids:
                f = registry.feature(fid)
                if not f:
                    continue
                governing_specs.append({
                    "id": f["id"], "title": f.get("title"), "summary": f.get("summary"),
                    "requirements": f.get("requirements") or [], "acceptance_criteria": f.get("acceptance_criteria") or [],
                    "invariants": f.get("invariants") or [],
                })
                all_requirement_ids.extend(r["id"] for r in (f.get("requirements") or []))
                all_acceptance_ids.extend(a["id"] for a in (f.get("acceptance_criteria") or []))
                all_invariant_ids.extend(i["id"] for i in (f.get("invariants") or []))
        except SpecError:
            pass

        design_kinds = ("ARCHITECTURE_ANALYSIS", "TECHNICAL_DESIGN", "UI_UX_DESIGN")
        design_context = []
        for wp in self.work_products.list_for_change(change_id):
            if wp["kind"] in design_kinds and wp["status"] == "APPROVED":
                design_context.append({"kind": wp["kind"], "id": wp["id"], "content": json.loads(wp["content_metadata"] or "{}")})

        existing_test_work = [
            {"kind": wp["kind"], "title": wp["title"], "status": wp["status"], "id": wp["id"]}
            for wp in self.work_products.list_for_change(change_id)
            if wp["kind"] in ("TEST_PLAN", "TEST_CASE_SET", "TEST_REVIEW", "REQUIREMENT_COVERAGE_REPORT") and wp["status"] != "SUPERSEDED"
        ]
        existing_test_cases = [
            {"key": tc["item_key"], "title": tc["title"], "test_level": tc["test_level"],
             "requirement_ids": json.loads(tc["requirement_ids"] or "[]")}
            for tc in self.test_case_specs.list_for_change(change_id)
        ]

        return {
            "change": {"id": change_id, "title": change.get("title") if change else None,
                       "original_intent": change.get("description") if change else None,
                       "change_type": change.get("change_type") if change else None},
            "governing_specs": governing_specs,
            "all_requirement_ids": sorted(set(all_requirement_ids)),
            "all_acceptance_ids": sorted(set(all_acceptance_ids)),
            "all_invariant_ids": sorted(set(all_invariant_ids)),
            "architecture_and_design": design_context,
            "project_test_command": project_test_command or {},
            "existing_test_work": existing_test_work,
            "existing_test_cases": existing_test_cases,
        }


# ===================================================================
# Test Design (E7.4/E7.5) -- expected outcome always from spec, never
# from current implementation (this service has no repo-read path)
# ===================================================================
def _staleness_digest(context: dict) -> str:
    """E7.21: digest used for TEST_SPEC_STALE detection -- deliberately
    excludes project_test_command (caller-supplied per-request, not
    persisted anywhere retrievable for a later staleness re-check) so a
    staleness check that omits it never produces a false positive
    against a design call that included it."""
    stable = {k: v for k, v in context.items() if k != "project_test_command"}
    return hashlib.sha256(json.dumps(stable, sort_keys=True).encode()).hexdigest()


class TestDesignService(_TestAgentRole):
    def __init__(self, db, changes, work_products, invoker, roles_catalog, context_builder: TestDesignContextBuilder,
                 test_case_specs: TestCaseSpecStore, specs_root, repo_root):
        super().__init__(db, invoker, roles_catalog, "TEST_DESIGNER")
        self.changes = changes
        self.work_products = work_products
        self.context_builder = context_builder
        self.test_case_specs = test_case_specs
        self.specs_root = specs_root
        self.repo_root = repo_root

    def current_test_case_set(self, change_id: int) -> dict | None:
        rows = [wp for wp in self.work_products.list_for_change(change_id) if wp["kind"] == "TEST_CASE_SET" and wp["status"] != "SUPERSEDED"]
        return rows[-1] if rows else None

    def current_test_plan(self, change_id: int) -> dict | None:
        rows = [wp for wp in self.work_products.list_for_change(change_id) if wp["kind"] == "TEST_PLAN" and wp["status"] != "SUPERSEDED"]
        return rows[-1] if rows else None

    def _known_ids(self):
        from app.services.spec_registry import SpecRegistry, SpecError
        try:
            registry = SpecRegistry(self.specs_root).load()
            return set(registry.requirements.keys()), set(registry.acceptance.keys()), set(registry.invariants.keys())
        except SpecError:
            return set(), set(), set()

    def _store(self, change_id, provider, parsed, digest, supersedes_plan_id, supersedes_set_id) -> dict:
        change = self.changes.get(change_id)
        known_req, known_acc, known_inv = self._known_ids()

        plan_wp_id = self.work_products.create(
            kind="TEST_PLAN", title=f"Test Plan for {change['title'] if change else change_id}",
            project_id=change.get("project_id") if change else None, change_id=change_id, status="DRAFT",
            content_metadata={"strategy_summary": parsed.get("strategy_summary") or "",
                               "untestable_or_ambiguous_items": parsed.get("untestable_or_ambiguous_items") or [],
                               "implementation_spec_conflicts": parsed.get("implementation_spec_conflicts") or []},
            content_digest=digest, supersedes_id=supersedes_plan_id)

        set_wp_id = self.work_products.create(
            kind="TEST_CASE_SET", title=f"Test Cases for {change['title'] if change else change_id}",
            project_id=change.get("project_id") if change else None, change_id=change_id, status="DRAFT",
            content_ref=f"test_plan:{plan_wp_id}", supersedes_id=supersedes_set_id)

        with self.db.connect() as conn:
            keys_seen: set[str] = set()
            for i, tc in enumerate(parsed.get("test_cases") or []):
                key = (tc.get("key") or "").strip() or f"TC-{i+1}"
                if key in keys_seen:
                    key = f"{key}-{i+1}"
                keys_seen.add(key)
                req_ids = [r for r in _resolve_id_collisions_free(tc.get("requirement_ids")) if r in known_req]
                acc_ids = [a for a in _resolve_id_collisions_free(tc.get("acceptance_ids")) if a in known_acc]
                inv_ids = [v for v in _resolve_id_collisions_free(tc.get("invariant_ids")) if v in known_inv]
                test_level = (tc.get("test_level") or "").strip().upper()
                if test_level not in TEST_LEVELS:
                    test_level = "INTEGRATION"
                test_type = (tc.get("test_type") or "POSITIVE").strip().upper()
                if test_type not in TEST_TYPES:
                    test_type = "POSITIVE"
                conn.execute(
                    "INSERT OR IGNORE INTO test_case_specs(change_id,work_product_id,item_key,source_feature_id,requirement_ids,"
                    "acceptance_ids,invariant_ids,test_level,test_type,title,purpose,preconditions,setup,action,expected_results,"
                    "failure_expectations,data_requirements,environment_requirements,automation_candidate,execution_hint,status) "
                    "VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)",
                    (change_id, set_wp_id, key, tc.get("source_feature_id"), json.dumps(req_ids), json.dumps(acc_ids),
                     json.dumps(inv_ids), test_level, test_type, tc.get("title") or key, tc.get("purpose") or "",
                     tc.get("preconditions") or "", tc.get("setup") or "", tc.get("action") or "",
                     tc.get("expected_results") or "", tc.get("failure_expectations") or "", tc.get("data_requirements") or "",
                     tc.get("environment_requirements") or "", 1 if tc.get("automation_candidate", True) else 0,
                     tc.get("execution_hint") or "", "DRAFT"))

        hd_ids = []
        for hd in parsed.get("human_decisions") or []:
            hd_ids.append(HumanDecisionService(self.db).create(
                "work_product", set_wp_id, hd.get("question") or "", hd.get("reason") or "",
                hd.get("decision_type") or "OTHER"))

        task_id = self.db.execute(
            "INSERT INTO tasks(slug,title,description,status,change_id,task_type) VALUES(?,?,?,?,?,?)",
            (f"testdesign-{change_id}-{set_wp_id}", f"Test Design: {change['title'] if change else change_id}", "",
             "ACTIVE", change_id, "TEST_DESIGN"))
        self.work_products.link_task(task_id, plan_wp_id, "OUTPUT")
        self.work_products.link_task(task_id, set_wp_id, "OUTPUT")
        self.db.event("change", change_id, "TEST_DESIGN_CREATED",
                       f"plan={plan_wp_id} set={set_wp_id} cases={len(keys_seen)}")
        return {"outcome": "READY", "test_plan": self.work_products.get(plan_wp_id),
                "test_case_set": self.work_products.get(set_wp_id),
                "test_cases": self.test_case_specs.list_for_work_product(set_wp_id),
                "human_decision_ids": hd_ids, "task_id": task_id}

    def design(self, change_id: int, provider: str = "claude", project_test_command: dict | None = None) -> dict:
        change = self.changes.get(change_id)
        if not change:
            raise TestDesignError("Change not found")
        try:
            self._check_assignment(provider)
        except TestDesignError as exc:
            self.db.event("change", change_id, "TEST_DESIGN_ASSIGNMENT_INVALID", str(exc))
            return {"outcome": "ASSIGNMENT_INVALID", "test_plan": None, "message": str(exc)}

        context = self.context_builder.build(change_id, project_test_command=project_test_command)
        digest = _staleness_digest(context)
        prompt = TEST_DESIGNER_PREAMBLE + "\n\nContext:\n" + json.dumps(context, indent=2, sort_keys=True)
        try:
            raw_text = self.invoker.invoke(provider, prompt, TEST_DESIGN_JSON_SCHEMA, self.repo_root)
            parsed = json.loads(raw_text)
        except Exception as exc:
            self.db.event("change", change_id, "TEST_DESIGN_FAILED", str(exc)[:500])
            return {"outcome": "EXECUTION_FAILED", "test_plan": None, "message": str(exc)}
        if not isinstance(parsed, dict) or "strategy_summary" not in parsed or "test_cases" not in parsed:
            self.db.event("change", change_id, "TEST_DESIGN_OUTPUT_INVALID", "missing required fields")
            return {"outcome": "OUTPUT_INVALID", "test_plan": None, "message": "Missing strategy_summary/test_cases"}

        return self._store(change_id, provider, parsed, digest, None, None)

    def refine(self, test_case_set_wp_id: int, review_findings: dict, provider: str = "claude") -> dict:
        prior_set = self.work_products.get(test_case_set_wp_id)
        if not prior_set or prior_set["kind"] != "TEST_CASE_SET":
            raise TestDesignError("test_case_set_wp_id does not reference a TEST_CASE_SET WorkProduct")
        prior_plan = self.current_test_plan(prior_set["change_id"])
        change_id = prior_set["change_id"]
        context = self.context_builder.build(change_id)
        context["prior_test_cases"] = [
            {"key": tc["item_key"], "title": tc["title"], "test_level": tc["test_level"],
             "requirement_ids": json.loads(tc["requirement_ids"] or "[]"), "expected_results": tc["expected_results"]}
            for tc in self.test_case_specs.list_for_work_product(test_case_set_wp_id)
        ]
        context["review_findings"] = review_findings
        digest = _staleness_digest(context)
        prompt = (TEST_DESIGNER_PREAMBLE +
                  "\n\nYou are REFINING a prior test design based on independent review findings below. Address "
                  "every finding. Never remove a difficult test case or requirement coverage merely to make "
                  "review easier -- only strengthen, clarify, or add.\n\nContext:\n" + json.dumps(context, indent=2, sort_keys=True))
        try:
            self._check_assignment(provider)
            raw_text = self.invoker.invoke(provider, prompt, TEST_DESIGN_JSON_SCHEMA, self.repo_root)
            parsed = json.loads(raw_text)
        except TestDesignError as exc:
            self.db.event("change", change_id, "TEST_DESIGN_REFINE_ASSIGNMENT_INVALID", str(exc))
            return {"outcome": "ASSIGNMENT_INVALID", "test_plan": None, "message": str(exc)}
        except Exception as exc:
            self.db.event("change", change_id, "TEST_DESIGN_REFINE_FAILED", str(exc)[:500])
            return {"outcome": "EXECUTION_FAILED", "test_plan": None, "message": str(exc)}
        if not isinstance(parsed, dict) or "strategy_summary" not in parsed or "test_cases" not in parsed:
            self.db.event("change", change_id, "TEST_DESIGN_REFINE_OUTPUT_INVALID", "missing required fields")
            return {"outcome": "OUTPUT_INVALID", "test_plan": None, "message": "Missing strategy_summary/test_cases"}

        result = self._store(change_id, provider, parsed, digest, prior_plan["id"] if prior_plan else None, test_case_set_wp_id)
        if result["outcome"] == "READY":
            self.work_products.set_status(test_case_set_wp_id, "SUPERSEDED")
            self.test_case_specs.set_status_for_work_product(test_case_set_wp_id, "SUPERSEDED")
            if prior_plan:
                self.work_products.set_status(prior_plan["id"], "SUPERSEDED")
        return result



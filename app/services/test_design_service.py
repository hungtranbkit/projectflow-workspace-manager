# Independent Test Review (E7.10) -- a fresh invocation, reviews the
# real deterministic coverage report, never a model-claimed one
# ===================================================================
class TestReviewService(_TestAgentRole):
    def __init__(self, db, changes, work_products, invoker, roles_catalog, test_case_specs: TestCaseSpecStore,
                 coverage_service: RequirementCoverageService, specs_root, repo_root, human_decisions: HumanDecisionService):
        super().__init__(db, invoker, roles_catalog, "REVIEWER")
        self.changes = changes
        self.work_products = work_products
        self.test_case_specs = test_case_specs
        self.coverage_service = coverage_service
        self.specs_root = specs_root
        self.repo_root = repo_root
        self.human_decision_service = human_decisions

    def review(self, test_case_set_wp_id: int, provider: str = "claude") -> dict:
        from app.services.spec_registry import SpecRegistry, SpecError
        test_set = self.work_products.get(test_case_set_wp_id)
        if not test_set or test_set["kind"] != "TEST_CASE_SET":
            raise TestDesignError("test_case_set_wp_id does not reference a TEST_CASE_SET WorkProduct")
        try:
            self._check_assignment(provider)
        except TestDesignError as exc:
            self.db.event("change", test_set["change_id"], "TEST_REVIEW_ASSIGNMENT_INVALID", str(exc))
            return {"outcome": "ASSIGNMENT_INVALID", "verdict": None, "message": str(exc)}

        change_id = test_set["change_id"]
        change = self.changes.get(change_id)
        cases = self.test_case_specs.list_for_work_product(test_case_set_wp_id)
        coverage = self.coverage_service.compute(change_id)
        plan_wp = self.db.one("SELECT * FROM work_products WHERE kind='TEST_PLAN' AND change_id=? AND status!='SUPERSEDED' ORDER BY id DESC LIMIT 1", (change_id,))
        governing_specs = []
        try:
            registry = SpecRegistry(self.specs_root).load()
            for fid in self.coverage_service.governing_feature_ids(change_id):
                f = registry.feature(fid)
                if f:
                    governing_specs.append({"id": f["id"], "title": f.get("title"),
                                             "requirements": f.get("requirements"), "acceptance_criteria": f.get("acceptance_criteria"),
                                             "invariants": f.get("invariants")})
        except SpecError:
            pass
        # Deliberately the REAL, independently-computed coverage report
        # (RequirementCoverageService.compute) -- never a model-claimed
        # coverage summary (E7.10: review dimensions include requirement
        # trace correctness, which this makes checkable against ground
        # truth, not against the author's own claim).
        context = {"original_intent": change.get("description") or change.get("title") if change else None,
                   "governing_specs": governing_specs,
                   "test_strategy_summary": json.loads(plan_wp["content_metadata"] or "{}").get("strategy_summary") if plan_wp else None,
                   "test_cases": [{"key": tc["item_key"], "title": tc["title"], "test_level": tc["test_level"],
                                    "test_type": tc["test_type"], "requirement_ids": json.loads(tc["requirement_ids"] or "[]"),
                                    "acceptance_ids": json.loads(tc["acceptance_ids"] or "[]"), "invariant_ids": json.loads(tc["invariant_ids"] or "[]"),
                                    "preconditions": tc["preconditions"], "action": tc["action"], "expected_results": tc["expected_results"],
                                    "failure_expectations": tc["failure_expectations"], "automation_candidate": bool(tc["automation_candidate"])}
                                   for tc in cases],
                   "deterministic_coverage_report": coverage}
        prompt = TEST_REVIEWER_PREAMBLE + "\n\nContext:\n" + json.dumps(context, indent=2, sort_keys=True)
        try:
            raw_text = self.invoker.invoke(provider, prompt, TEST_REVIEW_JSON_SCHEMA, self.repo_root)
            parsed = json.loads(raw_text)
        except Exception as exc:
            self.db.event("change", change_id, "TEST_REVIEW_FAILED", str(exc)[:500])
            return {"outcome": "EXECUTION_FAILED", "verdict": None, "message": str(exc)}
        if not isinstance(parsed, dict) or parsed.get("verdict") not in REVIEW_VERDICTS:
            self.db.event("change", change_id, "TEST_REVIEW_OUTPUT_INVALID", "missing/unknown verdict")
            return {"outcome": "OUTPUT_INVALID", "verdict": None, "message": "Missing or unknown verdict"}

        coverage_wp_id = self.work_products.create(
            kind="REQUIREMENT_COVERAGE_REPORT", title=f"Requirement Coverage for {change['title'] if change else change_id}",
            project_id=test_set["project_id"], change_id=change_id, status="APPROVED", content_metadata=coverage)
        review_wp_id = self.work_products.create(
            kind="TEST_REVIEW", title=f"Test Review: {test_set['title']}",
            project_id=test_set["project_id"], change_id=change_id, status="DRAFT", content_metadata=parsed)
        task_id = self.db.execute(
            "INSERT INTO tasks(slug,title,description,status,change_id,task_type) VALUES(?,?,?,?,?,?)",
            (f"testreview-{test_case_set_wp_id}-{review_wp_id}", f"Test Review: {test_set['title']}", "",
             "ACTIVE", change_id, "TEST_DESIGN"))
        self.work_products.link_task(task_id, review_wp_id, "OUTPUT")

        verdict = parsed["verdict"]
        hd_ids = []
        if verdict == "PASS":
            self.work_products.set_status(test_case_set_wp_id, "APPROVED")
            self.test_case_specs.set_status_for_work_product(test_case_set_wp_id, "APPROVED")
            if plan_wp:
                self.work_products.set_status(plan_wp["id"], "APPROVED")
        elif verdict == "REJECT":
            self.work_products.set_status(test_case_set_wp_id, "REJECTED")
            self.test_case_specs.set_status_for_work_product(test_case_set_wp_id, "REJECTED")
        elif verdict == "HUMAN_DECISION_REQUIRED":
            for hd in parsed.get("human_decisions") or []:
                hd_ids.append(self.human_decision_service.create(
                    "work_product", test_case_set_wp_id, hd.get("question") or "", hd.get("reason") or "", "OTHER"))

        self.db.event("change", change_id, "TEST_REVIEWED", f"test_case_set={test_case_set_wp_id} verdict={verdict}")
        return {"outcome": "REVIEWED", "verdict": verdict, "findings": parsed.get("findings") or [],
                "coverage": coverage, "human_decision_ids": hd_ids,
                "work_product": self.work_products.get(review_wp_id), "coverage_work_product": self.work_products.get(coverage_wp_id)}



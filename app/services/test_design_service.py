# Executable Test Mapping (E7.13/E7.14) -- explicit, human/API-confirmed
# linkage only, never unreliable semantic repo-wide guessing
# ===================================================================
class ExecutableTestMappingService:
    def __init__(self, db, test_case_specs: TestCaseSpecStore):
        self.db = db
        self.test_case_specs = test_case_specs

    def get(self, test_case_spec_id: int) -> dict | None:
        return self.db.one("SELECT * FROM test_executable_mappings WHERE test_case_spec_id=?", (test_case_spec_id,))

    def map(self, test_case_spec_id: int, repository_id: int | None, repository_path: str, test_symbol: str,
             command: str = "", framework: str = "", mapped_by: str = "HUMAN") -> dict:
        tc = self.test_case_specs.get(test_case_spec_id)
        if not tc:
            raise TestDesignError("TestCaseSpec not found")
        if not (repository_path or "").strip() or not ((test_symbol or "").strip() or (command or "").strip()):
            raise TestDesignError("Mapping requires an explicit repository_path and test_symbol/command -- E7.14: no unreliable/implicit guessing")
        existing = self.get(test_case_spec_id)
        if existing:
            self.db.execute(
                "UPDATE test_executable_mappings SET repository_id=?,repository_path=?,test_symbol=?,command=?,framework=?,"
                "implementation_status='IMPLEMENTED',mapped_by=?,updated_at=CURRENT_TIMESTAMP WHERE test_case_spec_id=?",
                (repository_id, repository_path, test_symbol, command, framework, mapped_by, test_case_spec_id))
        else:
            self.db.execute(
                "INSERT INTO test_executable_mappings(test_case_spec_id,repository_id,repository_path,test_symbol,command,framework,implementation_status,mapped_by) "
                "VALUES(?,?,?,?,?,?,?,?)",
                (test_case_spec_id, repository_id, repository_path, test_symbol, command, framework, "IMPLEMENTED", mapped_by))
        self.db.event("task", test_case_spec_id, "TEST_EXECUTABLE_MAPPED", f"path={repository_path} symbol={test_symbol}")
        return self.get(test_case_spec_id)

    def record_result(self, test_case_spec_id: int, status: str, last_result_reference: str | None = None) -> dict:
        status = (status or "").strip().upper()
        if status not in ("PASS", "FAIL"):
            raise TestDesignError("record_result status must be PASS or FAIL -- a designed-but-unexecuted test is never recorded as either")
        existing = self.get(test_case_spec_id)
        if not existing:
            raise TestDesignError("No executable mapping exists for this TestCaseSpec yet -- map it before recording a result")
        self.db.execute(
            "UPDATE test_executable_mappings SET implementation_status=?,last_result_reference=?,updated_at=CURRENT_TIMESTAMP WHERE test_case_spec_id=?",
            (status, last_result_reference, test_case_spec_id))
        return self.get(test_case_spec_id)

    def status_for_change(self, change_id: int) -> list[dict]:
        out = []
        for tc in self.test_case_specs.list_for_change(change_id):
            m = self.get(tc["id"])
            out.append({"test_case_spec_id": tc["id"], "item_key": tc["item_key"],
                         "implementation_status": m["implementation_status"] if m else "UNIMPLEMENTED",
                         "mapping": m})
        return out


def test_design_state_digest(work_products, change_id: int) -> str | None:
    """E7.16: a digest of the CURRENT (non-SUPERSEDED) test-design
    WorkProduct state governing a Change -- used by PlannerService to
    detect PLAN_TEST_DESIGN_STALE, mirroring E6.17's design_state_digest
    exactly."""
    kinds = ("TEST_PLAN", "TEST_CASE_SET", "TEST_REVIEW", "REQUIREMENT_COVERAGE_REPORT")
    rows = [wp for wp in work_products.list_for_change(change_id) if wp["kind"] in kinds and wp["status"] != "SUPERSEDED"]
    if not rows:
        return None
    fingerprint = sorted((wp["kind"], wp["id"], wp["status"], wp["updated_at"]) for wp in rows)
    return hashlib.sha256(json.dumps(fingerprint, sort_keys=True).encode()).hexdigest()



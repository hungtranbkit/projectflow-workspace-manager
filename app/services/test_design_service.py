"""Test Design, Requirement Coverage & Executable Acceptance Mapping
(Phase E7): Approved Spec -> Acceptance Criteria -> Test Design ->
Requirement Coverage -> Executable Test Mapping -> Test Review ->
TEST_DESIGN_READY.

CRITICAL SEPARATION, enforced by construction across five classes,
mirroring E5/E6's own AUTHOR/ARTIFACT/REVIEWER/APPROVAL separation
(E7's own instruction: keep SPEC / TEST SPECIFICATION / EXECUTABLE TEST
/ TEST RESULT / SPEC COMPLIANCE separate -- never a single "tests
passed" boolean):

  TEST SPECIFICATION (HOW behavior will be proven) -- TestDesignService
    + the test_case_specs table. One bounded, stateless, tool-less
    PlannerAgentInvoker.invoke() call (the same shared mechanism E4/E5/
    E6 use) that returns STRUCTURED TestCaseSpecs. Expected outcome is
    always taken from the approved Requirement/AcceptanceCriterion/
    Invariant text handed to it, never derived from current
    implementation (E7.5) -- this service has no repository-code
    reading path at all, so there is nothing for it to derive from.

  REQUIREMENT COVERAGE (deterministic, never trusts the model) --
    RequirementCoverageService. Recomputes requirements_covered/
    uncovered, acceptance_covered/uncovered, invariants_covered/
    uncovered directly from real SpecRegistry ids cross-referenced
    against the TestCaseSpecs' own requirement_ids/acceptance_ids/
    invariant_ids columns. A model-claimed coverage total is never
    trusted as authoritative (matches TechnicalDesignService's own
    covered_requirements/uncovered_requirements precedent, E6.9).

  TEST REVIEW (independent invocation) -- TestReviewService. A
    COMPLETELY SEPARATE invoke() call reviewing the TestCaseSpecs
    against the real coverage report, never the author's own reasoning.

  EXECUTABLE TEST MAPPING (a TestCaseSpec's implementation, not its
    result) -- ExecutableTestMappingService + test_executable_mappings.
    Explicit, human/API-confirmed linkage only (E7.14: no unreliable
    semantic repo-wide guessing); UNIMPLEMENTED/IMPLEMENTED/PASS/FAIL
    are the only states this module ever writes.

  TEST RESULT / SPEC COMPLIANCE -- untouched here. test_runs/
  verification_reports/EvidenceStore/SpecComplianceVerifier remain the
  ONLY place a test actually ran and what it proved is recorded --
  see app/services/spec_compliance.py's own E7 additions for how a
  designed-but-never-executed TestCaseSpec is distinguished from real
  execution evidence. A TestCaseSpec, however completely designed, is
  NEVER itself treated as evidence that anything actually passed.

No implementation Task is ever generated by this module (E7.15) --
Planner (E4) remains the only thing that ever creates a Task; this
module only exposes test_implementation_required/unimplemented_test_cases
to PlannerContextBuilder (see app/services/planner_service.py)."""


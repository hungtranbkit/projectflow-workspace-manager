# TestDesignLifecycleService -- bounded refinement loop (E7.11) + read
# helpers + WorkflowService gate evidence (E7.17) + Planner metadata
# (E7.15/E7.16)
# ===================================================================
class TestDesignLifecycleService:
    MAX_ROUNDS = 3

    def __init__(self, db, changes, work_products, trace, context_builder: TestDesignContextBuilder,
                 test_design: TestDesignService, coverage: RequirementCoverageService, review: TestReviewService,
                 test_case_specs: TestCaseSpecStore, executable_mapping: ExecutableTestMappingService,
                 human_decisions: HumanDecisionService, workflow_service=None):
        self.db = db
        self.changes = changes
        self.work_products = work_products
        self.trace = trace
        self.context_builder = context_builder
        self.test_design = test_design
        self.coverage = coverage
        self.review = review
        self.test_case_specs = test_case_specs
        self.executable_mapping = executable_mapping
        self.human_decision_service = human_decisions
        self.workflow_service = workflow_service

    # ---- read -----------------------------------------------------
    def current_test_case_set(self, change_id: int) -> dict | None:
        return self.test_design.current_test_case_set(change_id)

    def current_test_plan(self, change_id: int) -> dict | None:
        return self.test_design.current_test_plan(change_id)

    def unimplemented_test_cases(self, change_id: int) -> list[dict]:
        return [s for s in self.executable_mapping.status_for_change(change_id) if s["implementation_status"] == "UNIMPLEMENTED"]

    def status(self, change_id: int) -> dict:
        test_set = self.current_test_case_set(change_id)
        plan = self.current_test_plan(change_id)
        coverage_report = self.coverage.compute(change_id)
        unimplemented = self.unimplemented_test_cases(change_id)
        return {
            "change_id": change_id, "test_plan": plan, "test_case_set": test_set,
            "coverage": coverage_report, "test_implementation_required": bool(unimplemented),
            "unimplemented_test_cases": unimplemented,
            "test_design_ready": self.test_design_ready(change_id),
        }

    def _resolve_profile_key(self, change_id: int) -> str | None:
        if not self.workflow_service:
            return None
        run = self.workflow_service.get_workflow(change_id)
        return run["profile_key"] if run else None

    # ---- WorkflowService gate evidence (E7.17) ------------------------
    def test_design_ready(self, change_id: int, profile_key: str | None = None) -> bool:
        governing_ids = self.coverage.governing_feature_ids(change_id)
        if not governing_ids:
            # E7.17/E7.7: nothing governs this Change at the Change-level
            # spec trace-link -- vacuously ready, the same "nothing to
            # require" direction E6's architecture/design gates use.
            return True
        test_set = self.current_test_case_set(change_id)
        if not test_set or test_set["status"] != "APPROVED":
            return False
        if self.human_decision_service.pending_for_change(change_id):
            return False
        coverage_report = self.coverage.compute(change_id)
        if coverage_report["requirements_uncovered"]:
            return False
        profile_key = profile_key if profile_key is not None else self._resolve_profile_key(change_id)
        if profile_key == "CONTROLLED":
            if coverage_report["acceptance_uncovered"]:
                return False
            if coverage_report["invariants_total"] and coverage_report["invariants_uncovered"]:
                return False
        return True

    # ---- staleness (E7.21) --------------------------------------------
    def staleness(self, change_id: int) -> dict:
        """TEST_SPEC_STALE: the bounded context (governing spec text +
        approved architecture/design) that produced the CURRENT
        TestCaseSet has changed since generation -- a minimal digest-
        based check, same discipline as E5/E6 (never auto-deletes a
        test). EXECUTABLE_TEST_MAPPING_STALE: an executable mapping
        whose TestCaseSpec has since been SUPERSEDED by a refinement."""
        test_set = self.current_test_case_set(change_id)
        test_spec_stale = False
        current_digest = stored_digest = None
        if test_set:
            stored_digest = test_set.get("content_digest")
            current_context = self.context_builder.build(change_id)
            current_digest = _staleness_digest(current_context)
            test_spec_stale = bool(stored_digest) and stored_digest != current_digest
        stale_mappings = []
        for tc in self.test_case_specs.list_for_change(change_id, current_only=False):
            if tc["status"] != "SUPERSEDED":
                continue
            m = self.executable_mapping.get(tc["id"])
            if m:
                stale_mappings.append({"test_case_spec_id": tc["id"], "item_key": tc["item_key"]})
        return {
            "change_id": change_id,
            "test_spec_stale": test_spec_stale, "reason": "TEST_SPEC_STALE" if test_spec_stale else None,
            "stored_digest": stored_digest, "current_digest": current_digest,
            "executable_test_mapping_stale": stale_mappings,
        }

    # ---- bounded refinement loop (E7.11) ------------------------------
    def run_design(self, change_id: int, provider: str = "claude", max_rounds: int | None = None,
                    project_test_command: dict | None = None) -> dict:
        max_rounds = max_rounds if max_rounds is not None else self.MAX_ROUNDS
        result = self.test_design.design(change_id, provider=provider, project_test_command=project_test_command)
        if result["outcome"] != "READY":
            return {"outcome": result["outcome"], "stage": "TEST_DESIGN", "message": result.get("message"),
                    "test_case_set": None, "rounds": 0}
        set_id = result["test_case_set"]["id"]

        for round_no in range(max_rounds):
            review = self.review.review(set_id, provider=provider)
            if review["outcome"] != "REVIEWED":
                return {"outcome": review["outcome"], "stage": "TEST_REVIEW", "message": review.get("message"),
                        "test_case_set": self.work_products.get(set_id), "rounds": round_no}
            verdict = review["verdict"]
            if verdict == "PASS":
                return {"outcome": "TEST_DESIGN_READY", "test_case_set": self.work_products.get(set_id),
                        "coverage": review["coverage"], "verdict": verdict, "rounds": round_no + 1}
            if verdict in ("HUMAN_DECISION_REQUIRED", "REJECT"):
                return {"outcome": "HUMAN_DECISION_REQUIRED" if verdict == "HUMAN_DECISION_REQUIRED" else "REJECTED",
                        "test_case_set": self.work_products.get(set_id), "coverage": review["coverage"],
                        "verdict": verdict, "rounds": round_no + 1}
            if round_no + 1 >= max_rounds:
                return {"outcome": "NEEDS_REFINEMENT", "test_case_set": self.work_products.get(set_id),
                        "coverage": review["coverage"], "verdict": verdict, "rounds": round_no + 1,
                        "message": f"Refinement round limit ({max_rounds}) reached"}
            refined = self.test_design.refine(set_id, review, provider=provider)
            if refined["outcome"] != "READY":
                return {"outcome": refined["outcome"], "stage": "TEST_DESIGN_REFINE", "message": refined.get("message"),
                        "test_case_set": self.work_products.get(set_id), "rounds": round_no + 1}
            set_id = refined["test_case_set"]["id"]

        return {"outcome": "NEEDS_REFINEMENT", "test_case_set": self.work_products.get(set_id), "rounds": max_rounds}
